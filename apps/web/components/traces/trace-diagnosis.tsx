"use client";

import { Sparkles, Stethoscope } from "lucide-react";
import Link from "next/link";
import * as React from "react";
import { startInvestigation } from "@/app/actions";
import { useSpanSelection } from "@/components/traces/use-span-selection";
import { Button } from "@/components/ui/button";
import { Alert, Badge, Mono, Panel, PanelHeader } from "@/components/ui/primitives";
import type { Finding, Investigation, SpanSkeleton } from "@/lib/types";
import { cn, formatRelative } from "@/lib/utils";

const SEVERITY_TONE = { critical: "error", high: "error", medium: "warn", low: "info", info: "neutral" } as const;

type AiAnswer = {
  summary: string;
  insufficient_data: boolean;
  observations: { statement: string; kind: "fact" | "hypothesis"; span_ids: string[] }[];
  probable_root_cause: { statement: string; span_ids: string[]; confidence: "low" | "medium" | "high" } | null;
  next_steps: string[];
  unverified_span_ids?: string[];
};

function SpanChips({ ids, spans }: { ids: string[]; spans: Map<string, SpanSkeleton> }) {
  const [, select] = useSpanSelection();
  if (!ids.length) return null;
  return (
    <span className="mt-1.5 flex flex-wrap gap-1">
      {ids.slice(0, 8).map((id) => {
        const s = spans.get(id);
        return (
          <button
            key={id}
            type="button"
            onClick={() => select(id)}
            disabled={!s}
            title={s ? `Show span ${id}` : "Span not in this view"}
            className="inline-flex max-w-56 items-center gap-1 rounded-sm border border-border bg-surface-2 px-1.5 py-px font-mono text-[11px] text-muted-foreground hover:border-accent/60 hover:text-foreground disabled:opacity-50"
          >
            <span className="truncate">{s?.name ?? id}</span>
          </button>
        );
      })}
      {ids.length > 8 ? <span className="text-[11px] text-muted-foreground">+{ids.length - 8} more</span> : null}
    </span>
  );
}

function AiResult({ inv, spans }: { inv: Investigation; spans: Map<string, SpanSkeleton> }) {
  const ai = (inv.findings as { ai?: AiAnswer } | null)?.ai;
  const usage = (inv.findings as { usage?: { input_tokens?: number; output_tokens?: number } } | null)?.usage;
  if (!ai) return null;
  return (
    <div className="space-y-3">
      <p className="text-sm leading-6">{ai.summary}</p>
      {ai.insufficient_data ? (
        <Alert tone="warn">The model reported that this trace does not contain enough data to explain the failure.</Alert>
      ) : null}
      {ai.probable_root_cause ? (
        <div className="rounded-md border border-accent/40 bg-accent-soft/30 px-3 py-2">
          <p className="flex items-center gap-2 text-xs font-medium text-foreground">
            Probable root cause
            <Badge tone={ai.probable_root_cause.confidence === "high" ? "accent" : "neutral"}>
              {ai.probable_root_cause.confidence} confidence
            </Badge>
          </p>
          <p className="mt-1 text-sm">{ai.probable_root_cause.statement}</p>
          <SpanChips ids={ai.probable_root_cause.span_ids} spans={spans} />
        </div>
      ) : null}
      {ai.observations.length ? (
        <ul className="space-y-2">
          {ai.observations.map((o, i) => (
            <li key={i} className="text-sm">
              <Badge tone={o.kind === "fact" ? "ok" : "warn"} className="mr-2 align-[1px]">
                {o.kind === "fact" ? "Fact" : "Hypothesis"}
              </Badge>
              {o.statement}
              <SpanChips ids={o.span_ids} spans={spans} />
            </li>
          ))}
        </ul>
      ) : null}
      {ai.next_steps.length ? (
        <div>
          <p className="text-xs font-medium text-muted-foreground">Suggested next steps</p>
          <ol className="mt-1 list-decimal space-y-1 pl-5 text-sm">
            {ai.next_steps.map((s, i) => (
              <li key={i}>{s}</li>
            ))}
          </ol>
        </div>
      ) : null}
      <p className="text-[11px] text-muted-foreground">
        Generated by <Mono>{inv.model}</Mono> ({inv.provider})
        {usage?.input_tokens ? ` · ${usage.input_tokens} in / ${usage.output_tokens ?? 0} out tokens` : ""} ·{" "}
        {formatRelative(inv.completed_at ?? inv.created_at)}. Model output can be wrong; check the cited spans.
        {ai.unverified_span_ids?.length ? ` ${ai.unverified_span_ids.length} cited span IDs did not exist and were removed.` : ""}
      </p>
    </div>
  );
}

export function TraceDiagnosis({
  projectId,
  traceId,
  findings,
  initialInvestigations,
  spans,
  canRun,
  canConfigure,
}: {
  projectId: string;
  traceId: string;
  findings: Finding[];
  initialInvestigations: Investigation[];
  spans: SpanSkeleton[];
  canRun: boolean;
  canConfigure: boolean;
}) {
  const spanMap = React.useMemo(() => new Map(spans.map((s) => [s.span_id, s])), [spans]);
  const [latest, setLatest] = React.useState<Investigation | null>(
    () => initialInvestigations.find((i) => i.kind === "llm") ?? null,
  );
  const [starting, setStarting] = React.useState(false);
  const [error, setError] = React.useState<{ message: string; code?: string } | null>(null);
  const pending = latest && (latest.status === "queued" || latest.status === "running");

  React.useEffect(() => {
    if (!latest || !pending) return;
    let cancelled = false;
    const timer = setInterval(async () => {
      const res = await fetch(
        `/api/backend/projects/${encodeURIComponent(projectId)}/traces/${encodeURIComponent(traceId)}/investigations/${latest.id}`,
        { cache: "no-store" },
      ).catch(() => null);
      if (!res?.ok || cancelled) return;
      setLatest((await res.json()) as Investigation);
    }, 2000);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [latest, pending, projectId, traceId]);

  async function investigate() {
    setStarting(true);
    setError(null);
    const res = await startInvestigation(projectId, traceId, "ai");
    setStarting(false);
    if (res.ok) setLatest(res.data);
    else setError({ message: res.error, code: res.code });
  }

  return (
    <div className="grid items-start gap-4 lg:grid-cols-2">
      <Panel>
        <PanelHeader
          title={
            <span className="inline-flex items-center gap-2">
              <Stethoscope className="size-4 text-muted-foreground" /> Diagnosis
            </span>
          }
          description="Rule-based checks over this trace's spans. Always available, no model calls."
        />
        {findings.length === 0 ? (
          <p className="px-4 py-6 text-sm text-muted-foreground">No issues detected by the built-in rules.</p>
        ) : (
          <ul className="divide-y divide-border">
            {findings.map((f, i) => (
              <li key={`${f.rule}-${i}`} className="px-4 py-3">
                <div className="flex items-start gap-2">
                  <Badge tone={SEVERITY_TONE[f.severity]} className="mt-px capitalize">
                    {f.severity}
                  </Badge>
                  <div className="min-w-0">
                    <p className="text-sm font-medium">{f.title}</p>
                    <p className="mt-0.5 text-sm text-muted-foreground">{f.detail}</p>
                    <SpanChips ids={f.span_ids} spans={spanMap} />
                  </div>
                </div>
              </li>
            ))}
          </ul>
        )}
      </Panel>

      <Panel>
        <PanelHeader
          title={
            <span className="inline-flex items-center gap-2">
              <Sparkles className="size-4 text-muted-foreground" /> AI investigation
            </span>
          }
          description="Sends a redacted, size-limited summary of this trace to your configured model."
          actions={
            canRun ? (
              <Button size="sm" onClick={investigate} loading={starting || !!pending} disabled={starting || !!pending}>
                {latest ? "Run again" : "Investigate"}
              </Button>
            ) : null
          }
        />
        <div className={cn("px-4 py-3", !latest && !error && "py-6")}>
          {error ? (
            <Alert tone={error.code === "llm_not_configured" ? "info" : "error"} title="Investigation not started">
              {error.message}
              {error.code === "llm_not_configured" && canConfigure ? (
                <>
                  {" "}
                  <Link href={`/p/${projectId}/settings#providers`} className="text-accent hover:underline">
                    Add a provider key
                  </Link>
                </>
              ) : null}
            </Alert>
          ) : null}
          {!latest && !error ? (
            <p className="text-sm text-muted-foreground">
              {canRun
                ? "Ask a model to explain the failure. It cites span IDs for every observation and labels guesses as hypotheses."
                : "Viewers can read investigations but cannot start them."}
            </p>
          ) : null}
          {latest ? (
            latest.status === "completed" ? (
              <AiResult inv={latest} spans={spanMap} />
            ) : latest.status === "failed" ? (
              <Alert tone="error" title="Investigation failed">
                {latest.error ?? "The model call failed."}
              </Alert>
            ) : (
              <p className="flex items-center gap-2 text-sm text-muted-foreground" role="status">
                <span className="size-1.5 animate-pulse rounded-full bg-accent" />
                {latest.status === "queued" ? "Queued. Waiting for a worker…" : `Running on ${latest.model}…`}
              </p>
            )
          ) : null}
        </div>
      </Panel>
    </div>
  );
}
